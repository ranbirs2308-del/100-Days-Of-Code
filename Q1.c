// Write a program to input two numbers and display their sum.
#include <stdio.h>
int main()
{
    int a;
    printf("Enter the first number- ");
    scanf("%d", &a);
    int b;
    printf("Enter the second number- ");
    scanf("%d", &b);
    int c = a + b;
    printf("Sum of your 2 digits is %d", c);
    return 0;
}
